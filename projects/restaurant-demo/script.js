const menuToggle = document.querySelector(".menu-toggle");
const primaryNav = document.querySelector("#primary-nav");
const languageSwitch = document.querySelector(".language-switch");
const inquiryForm = document.querySelector("#event-form");
const formResponse = document.querySelector("#form-response");
const preferredDate = inquiryForm.querySelector('[name="date"]');
const today = new Date();
preferredDate.min = [
    today.getFullYear(),
    String(today.getMonth() + 1).padStart(2, "0"),
    String(today.getDate()).padStart(2, "0")
].join("-");

function setLanguage(language) {
    const selectedLanguage = translations[language] ? language : "en";
    const copy = translations[selectedLanguage];

    document.documentElement.lang = selectedLanguage;
    document.title = copy.pageTitle;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const translation = copy[element.dataset.i18n];
        if (translation !== undefined) element.textContent = translation;
    });

    document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
        element.dataset.i18nAttr.split(/\s+/).forEach((attributeTranslation) => {
            const [attribute, key] = attributeTranslation.split(":");
            if (copy[key] !== undefined) element.setAttribute(attribute, copy[key]);
        });
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        const translation = copy[element.dataset.i18nAria];
        if (translation !== undefined) element.setAttribute("aria-label", translation);
    });

    document.querySelectorAll("[data-language]").forEach((button) => {
        const isSelected = button.dataset.language === selectedLanguage;
        button.setAttribute("aria-pressed", String(isSelected));
    });

    if (formResponse.textContent) {
        formResponse.textContent = formResponse.classList.contains("is-error")
            ? getValidationMessage(inquiryForm.querySelector('[aria-invalid="true"]'), copy)
            : copy.formSuccess;
    }
}

function getValidationMessage(field, copy) {
    if (field.validity.valueMissing) return copy.formRequiredError;
    if (field.type === "email" && field.validity.typeMismatch) return copy.formEmailError;
    if (field.type === "number" && !field.validity.valid) return copy.formNumberError;
    if (field.type === "date" && !field.validity.valid) return copy.formDateError;
    return copy.formRequiredError;
}

function updateLanguage(language) {
    setLanguage(language);
    localStorage.setItem("majaliwa-restaurant-language", language);
}

languageSwitch.addEventListener("click", (event) => {
    const button = event.target.closest("[data-language]");
    if (button) updateLanguage(button.dataset.language);
});

menuToggle.addEventListener("click", () => {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-expanded", String(!isExpanded));
    primaryNav.classList.toggle("is-open", !isExpanded);
    menuToggle.setAttribute("aria-label", translations[document.documentElement.lang][
        isExpanded ? "openNavigation" : "closeNavigation"
    ]);
});

primaryNav.addEventListener("click", (event) => {
    if (event.target.closest("a")) {
        menuToggle.setAttribute("aria-expanded", "false");
        menuToggle.setAttribute("aria-label", translations[document.documentElement.lang].openNavigation);
        primaryNav.classList.remove("is-open");
    }
});

inquiryForm.addEventListener("input", (event) => {
    if (event.target.matches("input, select, textarea")) {
        event.target.removeAttribute("aria-invalid");
        event.target.removeAttribute("aria-describedby");
        formResponse.textContent = "";
        formResponse.classList.remove("is-error");
    }
});

inquiryForm.addEventListener("change", (event) => {
    if (event.target.matches("input, select, textarea")) {
        event.target.removeAttribute("aria-invalid");
        event.target.removeAttribute("aria-describedby");
        formResponse.textContent = "";
        formResponse.classList.remove("is-error");
    }
});

inquiryForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const invalidField = [...inquiryForm.elements].find((field) => field.willValidate && !field.validity.valid);

    if (invalidField) {
        const copy = translations[document.documentElement.lang];
        invalidField.focus();
        invalidField.setAttribute("aria-invalid", "true");
        invalidField.setAttribute("aria-describedby", "form-response");
        formResponse.textContent = getValidationMessage(invalidField, copy);
        formResponse.classList.add("is-error");
        return;
    }

    formResponse.textContent = translations[document.documentElement.lang].formSuccess;
    formResponse.classList.remove("is-error");
    inquiryForm.reset();
});

