function setLanguage(language) {
    const selected = translations[language] ? language : "en";
    const copy = translations[selected];
    document.documentElement.lang = selected;
    document.title = copy.pageTitle;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const translation = copy[element.dataset.i18n];
        if (translation !== undefined) element.innerHTML = translation;
    });

    document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
        for (const mapping of element.dataset.i18nAttr.split(/\s+/)) {
            const [attribute, key] = mapping.split(":");
            if (copy[key] !== undefined) element.setAttribute(attribute, copy[key]);
        }
    });
    if (menuButton) {
        const menuLabel = menuButton.getAttribute("aria-expanded") === "true" ? "menuClose" : "menuOpen";
        menuButton.setAttribute("aria-label", copy[menuLabel]);
    }

    languageSwitchers.forEach((button) => {
        const active = button.dataset.language === selected;
        button.setAttribute("aria-pressed", String(active));
        button.setAttribute("aria-label", copy[button.dataset.language === "en" ? "switchToEnglish" : "switchToSwahili"]);
    });

    try {
        localStorage.setItem("majaliwa-beauty-language", selected);
    } catch (error) {
        console.warn("Unable to save the preferred language.", error);
    }

    if (formStatus?.dataset.messageKey) {
        formStatus.textContent = copy[formStatus.dataset.messageKey];
    }
    appointmentForm?.querySelectorAll("input, select, textarea").forEach(updateFieldValidity);
}

languageSwitchers.forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
});

if (menuButton && navigation) {
    menuButton.addEventListener("click", () => {
        const expanded = menuButton.getAttribute("aria-expanded") === "true";
        menuButton.setAttribute("aria-expanded", String(!expanded));
        menuButton.setAttribute("aria-label", translations[document.documentElement.lang][expanded ? "menuOpen" : "menuClose"]);
        navigation.classList.toggle("is-open", !expanded);
    });

    navigation.addEventListener("click", (event) => {
        if (event.target.closest("a")) {
            navigation.classList.remove("is-open");
            menuButton.setAttribute("aria-expanded", "false");
            menuButton.setAttribute("aria-label", translations[document.documentElement.lang].menuOpen);
        }
    });

    document.addEventListener("keydown", (event) => {
        if (event.key === "Escape") {
            navigation.classList.remove("is-open");
            menuButton.setAttribute("aria-expanded", "false");
            menuButton.setAttribute("aria-label", translations[document.documentElement.lang].menuOpen);
        }
    });
}

function requestService(service) {
    if (serviceSelect && [...serviceSelect.options].some((option) => option.value === service)) {
        serviceSelect.value = service;
    }
    document.querySelector("#booking")?.scrollIntoView({ behavior: "smooth" });
    window.setTimeout(() => serviceSelect?.focus({ preventScroll: true }), 400);
}

document.querySelectorAll("[data-service], [data-book-service]").forEach((button) => {
    button.addEventListener("click", () => requestService(button.dataset.service || button.dataset.bookService));
});

function updateFieldValidity(field) {
    const copy = translations[document.documentElement.lang];
    let message = "";
    if (field.required && !field.value.trim()) message = copy.validationRequired;
    else if (field.type === "email" && field.value && field.validity.typeMismatch) message = copy.validationEmail;
    else if (field.name === "date" && field.value && field.value < field.min) message = copy.validationDate;
    field.setCustomValidity(message);
}

appointmentForm?.querySelectorAll("input, select, textarea").forEach((field) => {
    field.addEventListener("input", () => updateFieldValidity(field));
    field.addEventListener("change", () => updateFieldValidity(field));
});

appointmentForm?.addEventListener("submit", (event) => {
    event.preventDefault();
    appointmentForm.querySelectorAll("input, select, textarea").forEach(updateFieldValidity);
    if (!appointmentForm.reportValidity()) return;

    const formData = new FormData(appointmentForm);
    const subject = `${translations[document.documentElement.lang].submitAppointment} — ${serviceSelect.selectedOptions[0].textContent}`;
    const body = [
        `${translations[document.documentElement.lang].fieldName}: ${formData.get("name")}`,
        `${translations[document.documentElement.lang].fieldPhone}: ${formData.get("phone")}`,
        `${translations[document.documentElement.lang].fieldEmail}: ${formData.get("email")}`,
        `${translations[document.documentElement.lang].fieldService}: ${serviceSelect.selectedOptions[0].textContent}`,
        `${translations[document.documentElement.lang].fieldDate}: ${formData.get("date")}`,
        `${translations[document.documentElement.lang].fieldTime}: ${appointmentForm.querySelector('[name="time"]').selectedOptions[0].textContent}`,
        `${translations[document.documentElement.lang].fieldMessage}: ${formData.get("message") || "—"}`
    ].join("\n");

    if (formStatus) {
        formStatus.dataset.messageKey = "formSuccess";
        formStatus.textContent = translations[document.documentElement.lang].formSuccess;
    }
    window.location.href = `mailto:majaliway2@gmail.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
});

const dateInput = appointmentForm?.elements.namedItem("date");
if (dateInput instanceof HTMLInputElement) {
    const today = new Date();
    const localToday = new Date(today.getTime() - today.getTimezoneOffset() * 60000).toISOString().slice(0, 10);
    dateInput.min = localToday;
}

let preferredLanguage = "en";
try {
    preferredLanguage = localStorage.getItem("majaliwa-beauty-language") || "en";
} catch (error) {
    console.warn("Unable to read the preferred language.", error);
}
setLanguage(preferredLanguage);
